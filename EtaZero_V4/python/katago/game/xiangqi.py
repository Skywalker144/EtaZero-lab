"""Xiangqi's joint move vocabulary and physical-board transforms.

Ordering follows EtaZero V3.4. No legality is inferred from this static domain;
Pikafish owns piece movement, checks, repetitions and terminal adjudication.
"""

WIDTH, HEIGHT = 9, 10
HISTORY_FRAMES = 8
SPATIAL_FEATURES, GLOBAL_FEATURES = 1 + HISTORY_FRAMES * 14, 8


def _moves():
    moves = []
    for y in range(HEIGHT):
        for x in range(WIDTH):
            for v in range(HEIGHT):
                for u in range(WIDTH):
                    dx, dy = u - x, v - y
                    if (dx == 0) != (dy == 0) or sorted((abs(dx), abs(dy))) == [1, 2]:
                        moves.append((x, y, u, v))
    for flip in (False, True):
        for points, step in (([(3, 0), (5, 0), (4, 1), (3, 2), (5, 2)], 1),
                             ([(2, 0), (6, 0), (0, 2), (4, 2), (8, 2), (2, 4), (6, 4)], 2)):
            points = [(x, HEIGHT - 1 - y if flip else y) for x, y in points]
            moves.extend((x, y, u, v) for x, y in points for u, v in points
                         if abs(x - u) == step and abs(y - v) == step)
    return tuple(moves)


MOVES = _moves()
INDEX = {move: index for index, move in enumerate(MOVES)}
DELTAS = (tuple((0, d) for d in range(-9, 10) if d)
          + tuple((d, 0) for d in range(-8, 9) if d)
          + tuple((sx * d, sy * d) for d in (1, 2) for sx in (-1, 1) for sy in (-1, 1))
          + tuple((sx * a, sy * b) for a, b in ((1, 2), (2, 1)) for sx in (-1, 1) for sy in (-1, 1)))


def transform_move(move, *, black=False, mirror=False):
    x, y, u, v = move
    if black:
        x, y, u, v = WIDTH - 1 - x, HEIGHT - 1 - y, WIDTH - 1 - u, HEIGHT - 1 - v
    if mirror:
        x, u = WIDTH - 1 - x, WIDTH - 1 - u
    return x, y, u, v


def action_permutation(*, black=False, mirror=False):
    return tuple(INDEX[transform_move(move, black=black, mirror=mirror)] for move in MOVES)


def policy_indices(pos_len):
    if type(pos_len) is not int or pos_len < HEIGHT:
        raise ValueError('Xiangqi needs a canvas that contains its 9 x 10 board')
    delta_indices = {delta: index for index, delta in enumerate(DELTAS)}
    return tuple(delta_indices[u-x, v-y] * pos_len * pos_len + y * pos_len + x
                 for x, y, u, v in MOVES)


def cpp_header():
    moves = ',\n'.join('  {{' + ','.join(map(str, move)) + '}}' for move in MOVES)
    deltas = ','.join('{{' + ','.join(map(str, delta)) + '}}' for delta in DELTAS)
    return f'''// Generated by python/katago/game/xiangqi.py; do not edit the tables.
#ifndef GAME_XIANGQILAYOUT_H_
#define GAME_XIANGQILAYOUT_H_
#include <array>
namespace Xiangqi {{
constexpr int WIDTH = {WIDTH}, HEIGHT = {HEIGHT}, HISTORY_FRAMES = {HISTORY_FRAMES};
constexpr int SPATIAL_FEATURES = {SPATIAL_FEATURES}, GLOBAL_FEATURES = {GLOBAL_FEATURES};
constexpr int NUM_ACTIONS = {len(MOVES)}, NUM_DELTAS = {len(DELTAS)};
inline constexpr std::array<std::array<int,4>,NUM_ACTIONS> MOVES = {{{{
{moves}
}}}};
inline constexpr std::array<std::array<int,2>,NUM_DELTAS> DELTAS = {{{{{deltas}}}}};
}}
#endif
'''


if __name__ == '__main__':
    from pathlib import Path
    Path(__file__).resolve().parents[3].joinpath('cpp/game/xiangqilayout.h').write_text(cpp_header())
